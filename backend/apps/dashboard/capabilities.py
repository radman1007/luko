"""
دسترسی‌های داشبورد. هر کارمند فقط تیک‌هایی را دارد که مدیرِ کل برایش زده؛ مدیرِ کل
(superuser) همه را دارد و تنها کسی است که کارمند تعریف می‌کند.
"""

#: کلید → (عنوان، توضیح). ترتیبِ همین‌جا ترتیبِ نمایش در فرمِ تعریفِ کارمند است.
CAPABILITIES: dict[str, tuple[str, str]] = {
    "stats": ("آمار و نمای کلی", "خلاصه‌ی سایت، نمودارها، آنلاین‌ها و بازدیدها"),
    "users_view": ("دیدنِ کاربران", "فهرست، جستجو، فیلتر و جزئیاتِ هر کاربر"),
    "users_edit": ("ویرایشِ کاربران", "ویرایشِ نام و پایه، فعال/غیرفعال کردن، خروج از همه‌ی دستگاه‌ها"),
    "payments": ("پرداخت‌ها", "فهرستِ پرداخت‌ها و وضعیتِ اشتراک‌ها"),
    "gifts": ("هدیه‌ی اشتراک", "دادن و لغوِ اشتراکِ هدیه برای یک فرزند"),
    "tickets": ("پشتیبانی", "دیدن و پاسخ به تیکت‌های والدین"),
    "podcasts": ("پادکست‌ها", "افزودن، ویرایش و حذفِ پادکست"),
    "blog": ("وبلاگ", "نوشتن، ویرایش و انتشارِ پست‌های وبلاگ"),
    "learn": ("آموزشِ والدین", "مقاله، ویدیو و پادکستِ صفحه‌ی «آموزش» در پنلِ والدین"),
    "concepts": ("تگ‌های آموزشی", "تعریفِ تگ‌هایی که بازی‌ها روی هر پاسخ می‌فرستند و پنلِ والدین نشان می‌دهد"),
    "notify": ("ارسالِ اعلان", "فرستادنِ اعلان به والدین و دانش‌آموزان با فیلتر"),
    "audit": ("گزارشِ فعالیت‌ها", "دیدنِ کارهایی که تیم در داشبورد انجام داده"),
}

ALL = list(CAPABILITIES)

#: فقط مدیرِ کل
SUPERUSER = "superuser"


def clean(values) -> list[str]:
    """فهرستِ ورودی → فقط کلیدهای معتبر، بی‌تکرار و به ترتیبِ بالا."""
    chosen = set(values or [])
    return [key for key in ALL if key in chosen]


def of(user) -> list[str]:
    """دسترسی‌های واقعیِ یک کاربر (برای غیرکارمند خالی)."""
    if not (user and user.is_authenticated and user.is_active and user.is_staff):
        return []
    if user.is_superuser:
        return list(ALL)
    access = getattr(user, "staff_access", None)
    return clean(access.capabilities) if access else []
